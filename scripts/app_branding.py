from pathlib import Path
import subprocess

ROOT = Path("the_current_flutter")
MAIN = ROOT / "lib" / "main.dart"
MANIFEST = ROOT / "android" / "app" / "src" / "main" / "AndroidManifest.xml"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# Set the user-visible Android app label.
if MANIFEST.exists():
    s = MANIFEST.read_text(encoding="utf-8")
    import re
    s2 = re.sub(r'android:label="[^"]+"', 'android:label="News Feed"', s, count=1)
    MANIFEST.write_text(s2, encoding="utf-8")

# Rename visible starter branding throughout Dart UI files, including uppercase variants.
import re
LIB = ROOT / "lib"
for dart_file in LIB.rglob("*.dart"):
    s = dart_file.read_text(encoding="utf-8")
    s = re.sub(r"The Current\s*[-—:]\s*The News Feed", "News Feed", s, flags=re.IGNORECASE)
    s = re.sub(r"The Current", "News Feed", s, flags=re.IGNORECASE)
    dart_file.write_text(s, encoding="utf-8")

# Generate the supplied NF-style mark as a clean red/white launcher icon.
try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    raise SystemExit("Pillow is required to generate launcher icons")

sizes = {"mipmap-mdpi": 48, "mipmap-hdpi": 72, "mipmap-xhdpi": 96,
         "mipmap-xxhdpi": 144, "mipmap-xxxhdpi": 192}
for folder, size in sizes.items():
    target = RES / folder / "ic_launcher.png"
    if not target.parent.exists():
        continue
    im = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    d = ImageDraw.Draw(im)
    # Android adaptive icon-safe red circle, echoing the uploaded NF mark.
    pad = int(size * .06)
    d.ellipse((pad, pad, size-pad, size-pad), fill=(239, 18, 37, 255))
    try:
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", int(size*.42))
    except OSError:
        font = ImageFont.load_default()
    label = "NF"
    box = d.textbbox((0, 0), label, font=font, stroke_width=0)
    tw, th = box[2]-box[0], box[3]-box[1]
    d.text(((size-tw)/2, (size-th)/2-box[1]-size*.015), label, fill="white", font=font)
    im.save(target)

# Also update adaptive foreground when generated by flutter create.
for folder, size in sizes.items():
    target = RES / folder / "ic_launcher_foreground.png"
    if target.parent.exists():
        im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        pad = int(size * .17)
        d.ellipse((pad, pad, size-pad, size-pad), fill=(239, 18, 37, 255))
        try:
            font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", int(size*.35))
        except OSError:
            font = ImageFont.load_default()
        label = "NF"
        box = d.textbbox((0, 0), label, font=font)
        tw, th = box[2]-box[0], box[3]-box[1]
        d.text(((size-tw)/2, (size-th)/2-box[1]), label, fill="white", font=font)
        im.save(target)

print("Applied News Feed app label, title text replacements, and NF launcher icons.")
